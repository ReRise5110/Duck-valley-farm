export function createSampleFarmSet(): FarmData[] {
  const ts = Date.now();
  const today = new Date().toISOString().slice(0, 10);

  return SEED_FARMS.map((template, idx) => {
    const cloned = JSON.parse(JSON.stringify(template)) as FarmData;
    return {
      ...cloned,
      id: `sample-${ts}-${idx + 1}`,
      createdAt: today,
      lastSyncedAt: 'ยังไม่ซิงค์',
    };
  });
}

